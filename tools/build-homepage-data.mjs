import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { portalFacts, headline } from './portal-facts.mjs';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(WEB, 'index.html');
const BEGIN = '<!-- connected-data:begin (generated by tools/build-homepage-data.mjs) -->';
const END = '<!-- connected-data:end -->';
const LD_BEGIN = '<!-- jsonld:begin (generated by tools/build-homepage-data.mjs) -->';
const LD_END = '<!-- jsonld:end -->';

