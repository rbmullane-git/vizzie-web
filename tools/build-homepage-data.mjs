/**
 * build-homepage-data.mjs — fill the homepage's "Connected today" band from
 * the real numbers.
 *
 * That band — three headline stats, a curated list of portals with dataset
 * counts, and an "as at" date — was hand-typed HTML. It said 170 portals, 28
 * countries and "counts as at 6 Aug 2026" on 15 September, by which point
 * eight more portals were connected and several figures had moved by a lot
 * (data.gov.in reads 181,260 today against the 235,100 on the page — a
 * marketing claim ~30% above what the portal actually serves).
 *
 * So the *selection* stays editorial and the *numbers* stop being: the curated
 * lists below name portals by slug, and every count, total and date is read
 * from the build's own data through portal-facts.mjs.
 *
 * Usage:
 *   node tools/build-homepage-data.mjs           # rewrite the marked region
 *   node tools/build-homepage-data.mjs --check   # non-zero exit if stale
 */
