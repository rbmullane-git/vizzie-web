const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const num = (n) => (n == null ? '' : Number(n).toLocaleString('en-US'));

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
function longDate(iso) {
  const [y, m, d] = String(iso).split('-').map(Number);
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

const facts = portalFacts();
const byCountryCode = new Map();
for (const p of facts.portals) {
  if (!byCountryCode.has(p.countryCode)) byCountryCode.set(p.countryCode, []);
  byCountryCode.get(p.countryCode).push(p);
}

const missing = [];
const groupHtml = GROUPS.map((g) => {
  const rows = g.slugs.map((entry) => {
    const [slug, as] = Array.isArray(entry) ? entry : [entry, null];
    const p = facts.bySlug.get(slug);
    if (!p) { missing.push(slug); return null; }
    // Fall back to trimming the registry label's parenthetical, so a portal
    // added without a short name still renders reasonably.
    const name = as || p.name.replace(/\s*\([^)]*\)\s*$/, '');
    return `            <div class="prow"><span class="pn">${esc(name)}</span><span class="pc">${num(p.count)}</span></div>`;
  }).filter(Boolean);

  if (g.rest) {
    const shown = g.slugs.filter((e) => facts.bySlug.has(Array.isArray(e) ? e[0] : e)).length;
    const total = (byCountryCode.get(g.rest) || []).length;
    const more = total - shown;
    if (more > 0) {
      rows.push(`            <div class="prow"><span class="pn" style="color: var(--faint)">…and ${more} more</span><span class="pc"></span></div>`);
    }
  }
  if (g.tail) {
    rows.push(`            <div class="prow"><span class="pn">${esc(g.tail)}</span><span class="pc"></span></div>`);
  }
  return `          <div class="pgrp"><div class="phdr">${esc(g.heading)}</div>\n${rows.join('\n')}\n          </div>`;
}).join('\n');

if (missing.length) {
  process.stderr.write(`warn: no portal for slug(s): ${missing.join(', ')} — they may have been renamed\n`);
}

