function replaceRegion(source, begin, end, replacement, what) {
  const i = source.indexOf(begin);
  const j = source.indexOf(end);
  if (i === -1 || j === -1) {
    process.stderr.write(`index.html has no ${what} markers — add ${begin} / ${end}\n`);
    process.exit(1);
  }
  return source.slice(0, i) + replacement + source.slice(j + end.length);
}

// The deep-links page carries the same inline facts (data-fact spans), so it
// is refreshed by the same build — figures are never typed into a page by hand.
const LINK_PAGE = join(WEB, 'link', 'index.html');
if (existsSync(LINK_PAGE)) {
  const page = readFileSync(LINK_PAGE, 'utf8');
  const refreshed = applyInlineFacts(page);
  if (refreshed !== page && !process.argv.includes('--check')) {
    writeFileSync(LINK_PAGE, refreshed);
    process.stderr.write('link/index.html: facts refreshed\n');
  } else if (refreshed !== page) {
    process.stderr.write('link/index.html facts are stale\n');
    process.exit(1);
  }
}

const html = readFileSync(PAGE, 'utf8');
let next = replaceRegion(html, BEGIN, END, block, 'connected-data');
next = replaceRegion(next, LD_BEGIN, LD_END, ldBlock, 'jsonld');
next = applyInlineFacts(next);

if (process.argv.includes('--check')) {
  if (next !== html) { process.stderr.write('index.html connected-data band is stale\n'); process.exit(1); }
  process.stderr.write('index.html is up to date\n');
} else if (next === html) {
  process.stderr.write('index.html: unchanged\n');
} else {
  writeFileSync(PAGE, next);
  process.stderr.write(`index.html: updated — ${facts.portalCount} portals, ${facts.countryCount} countries, ${num(facts.datasetTotal)} datasets as at ${facts.asAt}\n`);
}
