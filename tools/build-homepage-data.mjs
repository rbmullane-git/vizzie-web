/**
 * Inline figures in prose outside the band. Marked with `data-fact` so the same
 * numbers can appear mid-sentence without becoming a second thing to remember
 * to update — the "thousands of open-data portals" this replaced overstated the
 * real figure by more than tenfold.
 */
const INLINE_FACTS = {
  'portal-count': String(facts.portalCount),
  'country-count': String(facts.countryCount),
  'dataset-total': `${headline(facts.datasetTotal)}+`,
};

function applyInlineFacts(source) {
  let out = source;
  // Not every fact has to appear inline; a key with no span is simply unused.
  for (const [key, value] of Object.entries(INLINE_FACTS)) {
    out = out.replace(new RegExp(`(<span data-fact="${key}">)[^<]*(</span>)`, 'g'), `$1${value}$2`);
  }
  return out;
}

